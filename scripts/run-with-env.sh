#!/usr/bin/env bash
# Wrapper that loads .env (overriding any system env vars) before running a command.
#
# ADR-008 (docs/DECISIONS.md): every db:* script, dev, build and start in
# package.json exec through here, so this is the single place where the
# Prisma datasource provider is resolved from the *effective* DATABASE_URL:
#
#   file:                       -> sqlite      (sandbox preview; generated,
#                                              gitignored variant schema)
#   postgres:// postgresql://   -> postgresql  (canonical committed schema —
#                                              CI e2e, docker-compose, Supabase)
#
# When the URL's provider differs from the one committed in
# prisma/schema.prisma, a variant schema (prisma/schema.local.prisma,
# gitignored) is regenerated with the URL's provider and `--schema <variant>`
# is injected into the prisma CLI invocation below. The committed schema file
# itself is NEVER modified, so the local override cannot leak into a commit
# (that leak — commit 76e2e51 — is what broke CI e2e with Prisma P1012).
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
ENV_FILE="$PROJECT_ROOT/.env"
if [[ -f "$ENV_FILE" ]]; then
  set -a
  . "$ENV_FILE"
  set +a
fi

# --- Prisma provider resolution (ADR-008) ------------------------------------

SCHEMA="$PROJECT_ROOT/prisma/schema.prisma"
LOCAL_SCHEMA="$PROJECT_ROOT/prisma/schema.local.prisma"

# Maps a DATABASE_URL to the Prisma provider its protocol implies.
# Returns non-zero for unknown/missing URLs (caller leaves everything alone).
url_provider() {
  case "${1:-}" in
    file:*)                      echo "sqlite" ;;
    postgres://*|postgresql://*) echo "postgresql" ;;
    *)                           return 1 ;;
  esac
}

# Extracts the provider declared inside the `datasource db { ... }` block.
schema_provider() {
  awk '
    /^datasource[ \t]+db[ \t]*\{/ { inblock = 1 }
    inblock && /^[ \t]*provider[ \t]*=/ {
      sub(/^[ \t]*provider[ \t]*=[ \t]*"/, "")
      sub(/".*$/, "")
      print
      exit
    }
    inblock && /^\}/ { inblock = 0 }
  ' "$1"
}

if [[ -f "$SCHEMA" ]] && url_provider "${DATABASE_URL:-}" > /dev/null; then
  WANT="$(url_provider "${DATABASE_URL:-}")"
  HAVE="$(schema_provider "$SCHEMA" || true)"
  if [[ -n "${HAVE:-}" && "${WANT}" != "${HAVE}" ]]; then
    # Regenerate the gitignored variant with the URL's provider (models are
    # copied verbatim; only the datasource provider line is swapped). Atomic
    # write: build in a sibling temp file, then move into place.
    TMP="$(mktemp "$PROJECT_ROOT/prisma/.schema.local.XXXXXX")"
    trap 'rm -f "$TMP"' EXIT
    {
      echo "// GENERATED by scripts/run-with-env.sh — do not edit, do not commit."
      echo "// Local ${WANT} variant of prisma/schema.prisma (matches this environment's"
      echo "// DATABASE_URL protocol). Canonical schema: prisma/schema.prisma — see"
      echo "// docs/DECISIONS.md, ADR-008."
      # NZ statutory engine (Phase 0): the canonical schema uses Postgres
      # native types (@db.Decimal(p, s) on EmployeeTaxProfile rate fields).
      # SQLite supports the Decimal scalar but NOT native type attributes
      # (Prisma P1012), so the generated variant strips them. Models are
      # still copied verbatim apart from the provider line and this strip.
      if [[ "$WANT" == "sqlite" ]]; then
        STRIP_NATIVE="-v strip_native=1"
      else
        STRIP_NATIVE=""
      fi
      awk -v provider="$WANT" $STRIP_NATIVE '
        BEGIN { if (strip_native) do_strip = 1 }
        do_strip { gsub(/[ \t]*@db\.Decimal\([0-9]+[ \t]*,[ \t]*[0-9]+\)/, "") }
        /^datasource[ \t]+db[ \t]*\{/ { inblock = 1 }
        inblock && !done && /^[ \t]*provider[ \t]*=/ {
          match($0, /provider[ \t]*=[ \t]*/)
          print substr($0, 1, RSTART - 1) "provider = \"" provider "\""
          done = 1
          next
        }
        inblock && /^\}/ { inblock = 0 }
        { print }
      ' "$SCHEMA"
    } > "$TMP"
    mv -f "$TMP" "$LOCAL_SCHEMA"
    trap - EXIT

    # Point the upcoming prisma CLI invocation at the variant — unless the
    # caller already picked a schema explicitly. Only the first few argv
    # slots are scanned: the CLI is always invoked as `prisma ...`,
    # `bunx prisma ...` or `.../node_modules/.bin/prisma ...`.
    # `--schema` is a per-subcommand flag in Prisma 6 (it is rejected as a
    # global flag before the subcommand), so it is APPENDED after the whole
    # command, which every db:/migrate: subcommand accepts.
    has_schema_arg="false"
    for a in "$@"; do
      case "$a" in
        --schema|--schema=*) has_schema_arg="true" ;;
      esac
    done
    if [[ "$has_schema_arg" == "false" ]]; then
      saw_prisma="false"
      i=0
      for a in "$@"; do
        i=$((i + 1))
        if [[ "$i" -gt 3 ]]; then break; fi
        if [[ "$a" == "prisma" || "$a" == */prisma ]]; then
          saw_prisma="true"
          break
        fi
      done
      if [[ "$saw_prisma" == "true" ]]; then
        set -- "$@" "--schema" "$LOCAL_SCHEMA"
        echo "run-with-env: DATABASE_URL implies provider '${WANT}' — prisma uses $LOCAL_SCHEMA" >&2
      fi
    fi
  fi
fi

exec "$@"
